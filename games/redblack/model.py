"""Small heads-up Red/Black, written from ~/coding/red_black/RULES.md.

This is an independent implementation of the rules (it does not import the
engine); `difftest.py` checks it against the engine mirror in
~/coding/red_black/simulator/src/redblack/engine.

A state is an immutable tuple-based record. The tree is generated by
`generate.py` from `children(state)`. Infoset keys are the acting player's
observation history: a list of tokens, each of which is something RULES.md
section 6 says that player sees. Getting that list right is the whole game
(Red/Black lessons.md #1), so every token is written in exactly one place,
`_observe`.

Knobs that differ from the real game are all in `Config`:
  * hand_size: cards dealt to each seat (the real game deals 5).
  * deck_red / deck_black: the deck the two hands are dealt from (the real
    game is 26/26; keeping 26/26 with a smaller hand keeps the real deal).
  * start: a fixed endgame position instead of a deal (every color public, as
    in the research's gate classes).
Everything else (reorder every round, locked-color bid ladder capped at the
cards in play, challenge only after a bid, the bidder flips any non-empty
deck top-down, first miss loses, reaching the count wins, the loser discards
privately, the procurement winner opens the next round, last player with
cards wins) is the standard rules, unchanged.

Two abstractions that change no value, both checked by difftest.py:
  * reorders are labeled by color sequence, not by card permutation
    (permutations that give the same color sequence lead to isomorphic
    subtrees and identical opponent views);
  * discards are labeled by color, not by card (after a discard the next
    round always opens with a reorder, and the opponent's view of a discard
    is the same whichever card left, RULES 4d and 6a).

`leak_discard=True` is a deliberately WRONG spec, kept as a mutant: the
opponent learns which slot the discarded card came from, which is what
stable card ids gave the v0 solver (lessons.md #1).
"""

from __future__ import annotations

from dataclasses import dataclass, field, replace
from fractions import Fraction
from itertools import permutations
from math import comb

R, B = "R", "B"
COLORS = (R, B)


@dataclass(frozen=True)
class Start:
    """A fixed position. Every card color is public (both players know both
    hands as multisets); hand ORDER is private and chosen at the reorder.

    phase "reorder": the round opens, `starter` will bid first.
    phase "discard": seat `loser` lost the last procurement and must discard,
    then the round opens with the winner (1 - loser) as starter.
    """

    hands: tuple[str, str]  # e.g. ("R", "RB"): seat 0 holds one red, seat 1 a red and a black
    phase: str = "reorder"
    starter: int = 0
    loser: int = -1


@dataclass(frozen=True)
class Config:
    name: str
    description: str
    hand_size: int | tuple[int, int] = 1  # an int deals that many to each seat
    deck_red: int = 26
    deck_black: int = 26
    start: Start | None = None
    leak_discard: bool = False
    # A seeded spec bug, for testing difftest.py itself (see MUTANTS). Never
    # used for a file in games/out.
    mutant: str = ""


MUTANTS = {
    "leak-reorder": "the opponent sees the color order a seat chose at its reorder",
    "forget-flips": "the challenger does not record the colors flipped in a procurement",
    "bid-cap-off-by-one": "a bid may not name every card in play (count < total instead of <=)",
    "starter-is-loser": "the procurement LOSER opens the next round",
    "color-switch": "a raise may switch color at a higher count",
    "reorder-round-1-only": "only round 1 has a reorder (the Locked Order variant, not the standard game)",
    "open-discard": "the opponent learns the COLOR of a discard (RULES 4d keeps it secret)",
}


@dataclass(frozen=True)
class State:
    hands: tuple[tuple[str, ...], tuple[str, ...]]
    phase: str  # "deal" | "reorder" | "bidding" | "procurement" | "discard" | "over"
    rnd: int = 1
    starter: int = 0
    reorder_left: tuple[int, ...] = ()
    active: int = 0
    bids: tuple[tuple[int, int, str], ...] = ()  # (by, count, color)
    # procurement: bidder, challenger, count, color, next index per seat, reds/blacks reached
    proc: tuple | None = None
    loser: int = -1
    winner: int = -1
    obs: tuple[tuple[str, ...], tuple[str, ...]] = ((), ())


def _observe(s: State, token_for: tuple[str | None, str | None]) -> State:
    """Append a token to each player's observation history (None: sees nothing)."""
    o0, o1 = s.obs
    if token_for[0] is not None:
        o0 = o0 + (token_for[0],)
    if token_for[1] is not None:
        o1 = o1 + (token_for[1],)
    return replace(s, obs=(o0, o1))


def _public(s: State, token: str) -> State:
    return _observe(s, (token, token))


def _private(s: State, seat: int, token: str) -> State:
    return _observe(s, (token, None) if seat == 0 else (None, token))


def infoset_key(s: State, player: int) -> str:
    return f"p{player}|" + " ".join(s.obs[player])


def total_in_play(s: State) -> int:
    return len(s.hands[0]) + len(s.hands[1])


# ---------------------------------------------------------------------------
# Root


def hand_sizes(cfg: Config) -> tuple[int, int]:
    h = cfg.hand_size
    return (h, h) if isinstance(h, int) else h


def deal_distribution(cfg: Config) -> list[tuple[int, int, Fraction]]:
    """(reds dealt to seat 0, reds dealt to seat 1, probability).

    Seat 0's hand is h0 cards drawn without replacement from the deck, seat
    1's the next h1; the rest are never seen. Only the color counts matter,
    because round 1 opens with a reorder of the whole hand.
    """
    h0, h1 = hand_sizes(cfg)
    nr, nb = cfg.deck_red, cfg.deck_black
    n = nr + nb
    if h0 + h1 > n:
        raise ValueError("deck too small for two hands")
    out = []
    for r0 in range(h0 + 1):
        p0 = Fraction(comb(nr, r0) * comb(nb, h0 - r0), comb(n, h0))
        if p0 == 0:
            continue
        for r1 in range(h1 + 1):
            p1 = Fraction(comb(nr - r0, r1) * comb(nb - (h0 - r0), h1 - r1), comb(n - h0, h1))
            if p1 == 0:
                continue
            out.append((r0, r1, p0 * p1))
    assert sum(p for _, _, p in out) == 1
    return out


def sorted_hand(reds: int, size: int) -> tuple[str, ...]:
    return (R,) * reds + (B,) * (size - reds)


def initial_state(cfg: Config) -> State:
    if cfg.start is None:
        return State(hands=((), ()), phase="deal")
    st = cfg.start
    hands = (tuple(sorted(st.hands[0], reverse=True)), tuple(sorted(st.hands[1], reverse=True)))
    pub = f"start:{''.join(hands[0])}|{''.join(hands[1])}"
    s = State(hands=hands, phase="deal")
    s = _public(s, pub)
    if st.phase == "reorder":
        return _open_round(s, st.starter, 1)
    assert st.phase == "discard" and st.loser in (0, 1)
    s = _public(s, f"L{st.loser}")
    return replace(s, phase="discard", active=st.loser, loser=st.loser)


def deal_children(cfg: Config) -> list[tuple[str, Fraction, State]]:
    out = []
    for r0, r1, p in deal_distribution(cfg):
        n0, n1 = hand_sizes(cfg)
        h0, h1 = sorted_hand(r0, n0), sorted_hand(r1, n1)
        s = State(hands=(h0, h1), phase="deal")
        s = _observe(s, (f"deal:{''.join(h0)}", f"deal:{''.join(h1)}"))
        out.append((f"{''.join(h0)}|{''.join(h1)}", p, _open_round(s, 0, 1)))
    return out


# ---------------------------------------------------------------------------
# Transitions


def _open_round(s: State, starter: int, rnd: int, cfg: Config | None = None) -> State:
    s = _public(s, f"r{rnd}:s{starter}")
    s = replace(s, phase="reorder", rnd=rnd, starter=starter, reorder_left=(0, 1), bids=(), proc=None, loser=-1)
    if cfg is not None and cfg.mutant == "reorder-round-1-only" and rnd > 1:
        s = replace(s, phase="bidding", reorder_left=(), active=starter)
    return s


def orderings(hand: tuple[str, ...]) -> list[tuple[str, ...]]:
    return sorted(set(permutations(hand)))


def player(s: State) -> int:
    if s.phase == "reorder":
        return s.reorder_left[0]
    return s.active


def legal(s: State, cfg: Config) -> list[tuple[str, State]]:
    """Labeled successors of a decision state, in a fixed order. A state with
    one successor is a forced move; generate.py skips it."""
    p = player(s)
    if s.phase == "reorder":
        out = []
        for order in orderings(s.hands[p]):
            hands = list(s.hands)
            hands[p] = order
            t = replace(s, hands=tuple(hands), reorder_left=s.reorder_left[1:])
            if cfg.mutant == "leak-reorder":
                t = _public(t, f"ro{p}:" + "".join(order))
            else:
                t = _private(t, p, "ro:" + "".join(order))
            if not t.reorder_left:
                t = replace(t, phase="bidding", active=t.starter)
            out.append(("".join(order), t))
        return out

    if s.phase == "bidding":
        total = total_in_play(s)
        out = []
        if s.bids:
            t = _public(s, f"{p}:ch")
            by, count, color = s.bids[-1]
            nxt = (0, 0)
            t = replace(t, phase="procurement", active=by, proc=(by, p, count, color, nxt, 0))
            out.append(("challenge", t))
            options = [(color, count + 1)]
            if cfg.mutant == "color-switch":
                options.append((B if color == R else R, count + 1))
        else:
            options = [(R, 1), (B, 1)]
        top = total if cfg.mutant == "bid-cap-off-by-one" else total + 1
        for color, lo in options:
            for count in range(lo, top):
                t = _public(s, f"{p}:{count}{color}")
                t = replace(t, bids=s.bids + ((p, count, color),), active=1 - p)
                out.append((f"bid {count}{color}", t))
        return out

    if s.phase == "procurement":
        bidder, challenger, count, color, nxt, got = s.proc
        out = []
        for target in (0, 1):
            idx = nxt[target]
            if idx >= len(s.hands[target]):
                continue
            card = s.hands[target][idx]
            if cfg.mutant == "forget-flips":
                t = _private(s, bidder, f"f{target}{card}")
            else:
                t = _public(s, f"f{target}{card}")
            nxt2 = tuple(i + 1 if k == target else i for k, i in enumerate(nxt))
            if card == color:
                got2 = got + 1
                if got2 >= count:
                    t = _resolve(t, cfg, loser=challenger)
                else:
                    t = replace(t, proc=(bidder, challenger, count, color, nxt2, got2))
                    unflipped = sum(len(t.hands[k]) - nxt2[k] for k in (0, 1))
                    if unflipped == 0:  # unreachable: a bid never exceeds the cards in play
                        t = _resolve(t, cfg, loser=bidder)
            else:
                t = _resolve(t, cfg, loser=bidder)
            out.append((f"flip{target}", t))
        return out

    if s.phase == "discard":
        L = s.loser
        hand = s.hands[L]
        out = []
        if cfg.leak_discard:
            for i, c in enumerate(hand):
                t = _observe(s, (f"d{L}@{i}",) * 2)
                out.append((f"discard slot{i}", _after_discard(t, cfg, i)))
            return out
        for c in sorted(set(hand), key=COLORS.index):
            i = max(k for k, x in enumerate(hand) if x == c)
            t = _private(s, L, f"dis:{c}")
            t = _private(t, 1 - L, f"d{L}{c}" if cfg.mutant == "open-discard" else f"d{L}")
            out.append((f"discard {c}", _after_discard(t, cfg, i)))
        return out

    raise ValueError(f"no decisions in phase {s.phase}")


def _resolve(s: State, cfg: Config, loser: int) -> State:
    s = _public(s, f"L{loser}")
    s = replace(s, phase="discard", active=loser, loser=loser, proc=None)
    if len(s.hands[loser]) == 1:  # forced discard, RULES 12
        return _after_discard(s, cfg, 0)
    return s


def _after_discard(s: State, cfg: Config, idx: int) -> State:
    L = s.loser
    hands = list(s.hands)
    hands[L] = hands[L][:idx] + hands[L][idx + 1 :]
    s = replace(s, hands=tuple(hands))
    if not hands[L]:
        return replace(s, phase="over", winner=1 - L)
    starter = L if cfg.mutant == "starter-is-loser" else 1 - L
    return _open_round(s, starter, s.rnd + 1, cfg)


def payoff_p0(s: State) -> int:
    assert s.phase == "over"
    return 1 if s.winner == 0 else -1
